import { describe, expect, it } from 'vitest'
import { readDataModel } from './dataModel'
import { arrow, entity, f } from './dataModel.fixtures'
import { planSchema, singular } from './schemaPlan'
import { boardToPostgres, quoteIdent } from './sql'
import { boardToPrisma, fieldIdent, modelIdent, prismaString } from './prisma'

const users = () => entity('u', 'users', [f('id', 'uuid', { pk: true }), f('email', 'text', { required: true, unique: true })])
const orders = () => entity('o', 'orders', [f('id', 'bigint', { pk: true }), f('total', 'float', { required: true })])

describe('quoteIdent', () => {
  it('quotes and doubles embedded quotes', () => {
    expect(quoteIdent('users')).toBe('"users"')
    expect(quoteIdent('say "hi"')).toBe('"say ""hi"""')
    expect(quoteIdent('x"; DROP TABLE users; --')).toBe('"x""; DROP TABLE users; --"')
    expect(quoteIdent('a\0b')).toBe('"ab"')
  })
})

describe('singular', () => {
  it.each([
    ['users', 'user'],
    ['categories', 'category'],
    ['status', 'status'],
    ['address', 'address'],
    ['person', 'person'],
    ['s', 's'],
  ])('%s → %s', (a, b) => expect(singular(a)).toBe(b))
})

describe('toPostgres', () => {
  it('creates tables with keys, NOT NULL and UNIQUE', () => {
    const sql = boardToPostgres('Shop', [users()])
    expect(sql).toContain('-- Generated by Co-Create from the board "Shop".')
    expect(sql).toContain(
      ['CREATE TABLE "users" (', '  "id" UUID NOT NULL,', '  "email" TEXT NOT NULL UNIQUE,', '  PRIMARY KEY ("id")', ');'].join('\n'),
    )
  })

  it('maps every field type', () => {
    const types = ['text', 'int', 'bigint', 'float', 'bool', 'date', 'timestamp', 'uuid', 'json'] as const
    const sql = boardToPostgres('', [entity('t', 't', types.map((ty) => f(`c_${ty}`, ty)))])
    for (const s of ['TEXT', 'INTEGER', 'BIGINT', 'DOUBLE PRECISION', 'BOOLEAN', 'DATE', 'TIMESTAMPTZ', 'UUID', 'JSONB']) {
      expect(sql).toContain(` ${s}`)
    }
  })

  it('escapes hostile table and column names and keeps comments on one line', () => {
    const sql = boardToPostgres('Evil\n DROP TABLE x;', [entity('e', 'my "table"', [f('col"; --', 'int', { pk: true })])])
    expect(sql).toContain('CREATE TABLE "my ""table""" (')
    expect(sql).toContain('"col""; --" INTEGER NOT NULL')
    expect(sql.split('\n')[0]).toBe('-- Generated by Co-Create from the board "Evil  DROP TABLE x;".')
  })

  it('names unnamed tables and columns and de-duplicates names', () => {
    const sql = boardToPostgres('', [
      entity('a', '', [f(''), f('x'), f('x')]),
      entity('b', 'dup', []),
      entity('c', 'dup', []),
    ])
    expect(sql).toContain('CREATE TABLE "table_1" (\n  "column_1" TEXT,\n  "x" TEXT,\n  "x_2" TEXT\n);')
    expect(sql).toContain('CREATE TABLE "dup" ();')
    expect(sql).toContain('CREATE TABLE "dup_2" ();')
  })

  it('adds a foreign-key column for one-to-many', () => {
    const sql = boardToPostgres('', [users(), orders(), arrow('r', 'u', 'o')])
    expect(sql).toContain('  "total" DOUBLE PRECISION NOT NULL,\n  "user_id" UUID,\n  PRIMARY KEY ("id")')
    expect(sql).toContain('ALTER TABLE "orders" ADD FOREIGN KEY ("user_id") REFERENCES "users" ("id");')
  })

  it('reuses a foreign-key field the user drew', () => {
    const o = entity('o', 'orders', [f('id', 'int', { pk: true }), f('user_id', 'uuid', { required: true })])
    const sql = boardToPostgres('', [users(), o, arrow('r', 'u', 'o')])
    expect(sql.match(/"user_id"/g)).toHaveLength(2) // the column, and the ALTER TABLE
    expect(sql).toContain('"user_id" UUID NOT NULL')
  })

  it('makes one-to-one foreign keys unique', () => {
    const sql = boardToPostgres('', [users(), entity('p', 'profiles', [f('id', 'int', { pk: true })]), arrow('r', 'u', 'p', '1-1')])
    expect(sql).toContain('"user_id" UUID UNIQUE')
  })

  it('creates a join table for many-to-many', () => {
    const tags = entity('t', 'tags', [f('id', 'int', { pk: true })])
    const sql = boardToPostgres('', [orders(), tags, arrow('r', 'o', 't', 'n-n')])
    expect(sql).toContain(
      [
        '-- Join table for a many-to-many relation.',
        'CREATE TABLE "orders_tags" (',
        '  "order_id" BIGINT NOT NULL,',
        '  "tag_id" INTEGER NOT NULL,',
        '  PRIMARY KEY ("order_id", "tag_id")',
        ');',
      ].join('\n'),
    )
    expect(sql).toContain('ALTER TABLE "orders_tags" ADD FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE;')
    expect(sql).toContain('ALTER TABLE "orders_tags" ADD FOREIGN KEY ("tag_id") REFERENCES "tags" ("id") ON DELETE CASCADE;')
  })

  it('handles self relations and composite keys', () => {
    const emp = entity('e', 'employees', [f('id', 'int', { pk: true })])
    const self = boardToPostgres('', [emp, arrow('r', 'e', 'e')])
    expect(self).toContain('"parent_employee_id" INTEGER')
    expect(self).toContain('REFERENCES "employees" ("id")')
    const friends = boardToPostgres('', [emp, arrow('r', 'e', 'e', 'n-n')])
    expect(friends).toContain('CREATE TABLE "employees_employees" (\n  "employee_id" INTEGER NOT NULL,\n  "related_employee_id" INTEGER NOT NULL,')

    const comp = entity('c', 'lines', [f('order', 'int', { pk: true }), f('n', 'int', { pk: true })])
    const sql = boardToPostgres('', [comp, entity('x', 'notes', []), arrow('r', 'c', 'x')])
    expect(sql).toContain('PRIMARY KEY ("order", "n")')
    expect(sql).toContain('ADD FOREIGN KEY ("line_order", "line_n") REFERENCES "lines" ("order", "n")')
  })

  it('gives two relations between the same tables separate columns', () => {
    const sql = boardToPostgres('', [users(), orders(), arrow('r1', 'u', 'o'), arrow('r2', 'u', 'o')])
    expect(sql).toContain('"user_id" UUID,\n  "user_id_2" UUID,')
  })

  it('skips a relation whose parent has no primary key, with a note', () => {
    const sql = boardToPostgres('', [entity('a', 'logs', [f('msg')]), orders(), arrow('r', 'a', 'o')])
    expect(sql).toContain('-- Note: Skipped the relation logs → orders: "logs" has no primary key to reference.')
    expect(sql).not.toContain('FOREIGN KEY')
  })

  it('says when there are no tables', () => {
    expect(boardToPostgres('', [])).toContain('-- The board has no tables yet.')
  })

  it('plans deterministically', () => {
    const model = readDataModel([users(), orders(), arrow('r', 'u', 'o', 'n-n')])
    expect(planSchema(model).tables.map((t) => t.name)).toEqual(['users', 'orders', 'users_orders'])
  })
})

describe('toPrisma', () => {
  it('makes valid identifiers and string literals', () => {
    expect(modelIdent('order items')).toBe('OrderItems')
    expect(modelIdent('2fa')).toBe('M2fa')
    expect(fieldIdent('first name')).toBe('first_name')
    expect(fieldIdent('1st')).toBe('f_1st')
    expect(prismaString('a "b" \\ c')).toBe('"a \\"b\\" \\\\ c"')
  })

  it('writes models with ids, maps and both sides of a relation', () => {
    const prisma = boardToPrisma('Shop', [users(), orders(), arrow('r', 'u', 'o')])
    expect(prisma).toContain('provider = "postgresql"')
    expect(prisma).toContain('model Users {\n  id String @id @db.Uuid\n  email String @unique')
    expect(prisma).toContain('  @@map("users")')
    expect(prisma).toContain('  user_id String? @db.Uuid')
    expect(prisma).toContain('  users Users? @relation("orders.user_id", fields: [user_id], references: [id])')
    expect(prisma).toContain('  ordersList Orders[] @relation("orders.user_id")')
  })

  it('uses @@id and explicit join models for many-to-many', () => {
    const tags = entity('t', 'tags', [f('id', 'int', { pk: true })])
    const prisma = boardToPrisma('', [orders(), tags, arrow('r', 'o', 't', 'n-n')])
    expect(prisma).toContain('model OrdersTags {')
    expect(prisma).toContain('  @@id([order_id, tag_id])')
    expect(prisma).toContain('onDelete: Cascade')
  })

  it('maps names that are not identifiers', () => {
    const prisma = boardToPrisma('', [entity('e', 'my table', [f('first name', 'text', { pk: true })])])
    expect(prisma).toContain('  first_name String @id @map("first name")')
    expect(prisma).toContain('  @@map("my table")')
  })

  it('marks one-to-one back relations as optional singles', () => {
    const prisma = boardToPrisma('', [users(), entity('p', 'profiles', [f('id', 'int', { pk: true })]), arrow('r', 'u', 'p', '1-1')])
    expect(prisma).toContain('  user_id String? @unique @db.Uuid')
    expect(prisma).toContain('  profiles Profiles? @relation("profiles.user_id")')
  })
})
