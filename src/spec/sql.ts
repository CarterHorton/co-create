/**
 * PostgreSQL DDL for the board's data model: one CREATE TABLE per entity
 * (and per many-to-many join table), then the foreign keys as ALTER TABLE
 * statements, so table order never matters. Every identifier is quoted.
 */

import type { BoardShape } from '@/components/board/types'
import { readDataModel, type DataModel, type FieldType } from './dataModel'
import { planSchema, type PlannedTable } from './schemaPlan'

export const POSTGRES_TYPES: Record<FieldType, string> = {
  text: 'TEXT',
  int: 'INTEGER',
  bigint: 'BIGINT',
  float: 'DOUBLE PRECISION',
  bool: 'BOOLEAN',
  date: 'DATE',
  timestamp: 'TIMESTAMPTZ',
  uuid: 'UUID',
  json: 'JSONB',
}

/** A quoted Postgres identifier: `say "hi"` → `"say ""hi"""`. NUL can't appear in one, so it's dropped. */
export function quoteIdent(name: string): string {
  return `"${name.replace(/\0/g, '').replace(/"/g, '""')}"`
}

const list = (cols: string[]) => cols.map(quoteIdent).join(', ')
/** One line of text safe inside a `--` comment. */
const commentText = (s: string) => s.replace(/[\r\n]+/g, ' ')

function createTable(t: PlannedTable): string {
  const lines = t.columns.map((c) => {
    const lone = t.uniques.some((u) => u.length === 1 && u[0] === c.name)
    return `  ${quoteIdent(c.name)} ${POSTGRES_TYPES[c.type]}${c.notNull ? ' NOT NULL' : ''}${lone ? ' UNIQUE' : ''}`
  })
  if (t.primaryKey.length) lines.push(`  PRIMARY KEY (${list(t.primaryKey)})`)
  for (const u of t.uniques) if (u.length > 1) lines.push(`  UNIQUE (${list(u)})`)
  const head = t.join ? '-- Join table for a many-to-many relation.\n' : ''
  if (!lines.length) return `${head}CREATE TABLE ${quoteIdent(t.name)} ();`
  return `${head}CREATE TABLE ${quoteIdent(t.name)} (\n${lines.join(',\n')}\n);`
}

export function toPostgres(model: DataModel, title = ''): string {
  const { tables, notes } = planSchema(model)
  const out: string[] = [
    `-- ${commentText(title.trim() ? `Generated by Co-Create from the board "${title.trim()}".` : 'Generated by Co-Create.')}`,
    '-- PostgreSQL.',
  ]
  for (const n of notes) out.push(`-- Note: ${commentText(n)}`)
  out.push('')
  if (!tables.length) {
    out.push('-- The board has no tables yet.', '')
    return out.join('\n')
  }
  for (const t of tables) out.push(createTable(t), '')
  const fks = tables.flatMap((t) =>
    t.foreignKeys.map(
      (fk) =>
        `ALTER TABLE ${quoteIdent(t.name)} ADD FOREIGN KEY (${list(fk.columns)}) REFERENCES ${quoteIdent(fk.table.name)} (${list(fk.references)})` +
        `${fk.onDelete ? ` ON DELETE ${fk.onDelete}` : ''};`,
    ),
  )
  if (fks.length) out.push(...fks, '')
  return out.join('\n')
}

export const boardToPostgres = (title: string, shapes: BoardShape[]) => toPostgres(readDataModel(shapes), title)
