/**
 * Prisma schema for the board's data model, from the same plan as the SQL
 * export: one model per table (join tables become explicit models), with
 * @map / @@map wherever a board name isn't a valid Prisma identifier, and a
 * named relation (both sides) for every foreign key.
 */

import type { BoardShape } from '@/components/board/types'
import { readDataModel, type DataModel, type FieldType } from './dataModel'
import { planSchema, type PlannedTable } from './schemaPlan'

const PRISMA_TYPES: Record<FieldType, { type: string; attr?: string }> = {
  text: { type: 'String' },
  int: { type: 'Int' },
  bigint: { type: 'BigInt' },
  float: { type: 'Float' },
  bool: { type: 'Boolean' },
  date: { type: 'DateTime', attr: '@db.Date' },
  timestamp: { type: 'DateTime', attr: '@db.Timestamptz' },
  uuid: { type: 'String', attr: '@db.Uuid' },
  json: { type: 'Json' },
}

/** A Prisma string literal. */
export const prismaString = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ')}"`

/** A valid Prisma field name: letters, digits and underscores, starting with a letter. */
export function fieldIdent(name: string): string {
  const s = name.replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '')
  return /^[A-Za-z]/.test(s) ? s : `f_${s || 'field'}`
}

/** A model name: "order items" → "OrderItems". */
export function modelIdent(name: string): string {
  const s = name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
  return /^[A-Za-z]/.test(s) ? s : `M${s || 'Model'}`
}

function uniqueIn(name: string, taken: Set<string>): string {
  let out = name
  for (let i = 2; taken.has(out.toLowerCase()); i++) out = `${name}${i}`
  taken.add(out.toLowerCase())
  return out
}

const lowerFirst = (s: string) => s[0].toLowerCase() + s.slice(1)

export function toPrisma(model: DataModel, title = ''): string {
  const { tables, notes } = planSchema(model)
  const modelNames = new Set<string>()
  const modelOf = new Map<PlannedTable, string>(tables.map((t) => [t, uniqueIn(modelIdent(t.name), modelNames)]))
  /** Per model: taken field names, and table column → Prisma field name. */
  const taken = new Map<PlannedTable, Set<string>>()
  const fieldOf = new Map<PlannedTable, Map<string, string>>()
  for (const t of tables) {
    const names = new Set<string>()
    taken.set(t, names)
    fieldOf.set(t, new Map(t.columns.map((c) => [c.name, uniqueIn(fieldIdent(c.name), names)])))
  }
  /** Relation lines to add to each model, after its columns. */
  const extra = new Map<PlannedTable, string[]>(tables.map((t) => [t, []]))
  for (const t of tables) {
    for (const fk of t.foreignKeys) {
      const target = fk.table
      const relName = prismaString(`${t.name}.${fk.columns.join('_')}`)
      const optional = fk.columns.some((c) => !t.columns.find((x) => x.name === c)!.notNull)
      const fieldName = uniqueIn(lowerFirst(modelOf.get(target)!), taken.get(t)!)
      const fields = fk.columns.map((c) => fieldOf.get(t)!.get(c)!).join(', ')
      const refs = fk.references.map((c) => fieldOf.get(target)!.get(c)!).join(', ')
      const onDelete = fk.onDelete === 'CASCADE' ? ', onDelete: Cascade' : ''
      extra.get(t)!.push(
        `  ${fieldName} ${modelOf.get(target)}${optional ? '?' : ''} @relation(${relName}, fields: [${fields}], references: [${refs}]${onDelete})`,
      )
      // The other side: a list, or (1–1) at most one.
      const back = uniqueIn(lowerFirst(modelOf.get(t)!) + (fk.oneToOne ? '' : 'List'), taken.get(target)!)
      extra.get(target)!.push(`  ${back} ${modelOf.get(t)}${fk.oneToOne ? '?' : '[]'} @relation(${relName})`)
    }
  }

  const out: string[] = [
    `// ${title.trim() ? `Generated by Co-Create from the board ${prismaString(title.trim())}.` : 'Generated by Co-Create.'}`,
    '// Set the connection URL in prisma.config.ts (Prisma 7) or add url = env("DATABASE_URL") here.',
  ]
  for (const n of notes) out.push(`// Note: ${n.replace(/[\r\n]+/g, ' ')}`)
  out.push('', 'datasource db {', '  provider = "postgresql"', '}', '')
  for (const t of tables) {
    const fields = fieldOf.get(t)!
    const lines: string[] = []
    if (!t.primaryKey.length) lines.push('  /// No primary key on the board: Prisma needs an @id or @unique field before it can use this model.')
    for (const c of t.columns) {
      const p = PRISMA_TYPES[c.type]
      const attrs: string[] = []
      if (t.primaryKey.length === 1 && t.primaryKey[0] === c.name) attrs.push('@id')
      if (t.uniques.some((u) => u.length === 1 && u[0] === c.name)) attrs.push('@unique')
      if (p.attr) attrs.push(p.attr)
      if (fields.get(c.name) !== c.name) attrs.push(`@map(${prismaString(c.name)})`)
      const optional = !c.notNull && !t.primaryKey.includes(c.name)
      lines.push(`  ${fields.get(c.name)} ${p.type}${optional ? '?' : ''}${attrs.length ? ` ${attrs.join(' ')}` : ''}`)
    }
    lines.push(...extra.get(t)!)
    const ids = (cols: string[]) => cols.map((c) => fields.get(c)!).join(', ')
    if (t.primaryKey.length > 1) lines.push(`  @@id([${ids(t.primaryKey)}])`)
    for (const u of t.uniques) if (u.length > 1) lines.push(`  @@unique([${ids(u)}])`)
    if (modelOf.get(t) !== t.name) lines.push(`  @@map(${prismaString(t.name)})`)
    out.push(`model ${modelOf.get(t)} {`, ...lines, '}', '')
  }
  return out.join('\n')
}

export const boardToPrisma = (title: string, shapes: BoardShape[]) => toPrisma(readDataModel(shapes), title)
